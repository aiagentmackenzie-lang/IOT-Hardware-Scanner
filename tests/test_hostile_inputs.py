"""Adversarial inputs through the installed CLI (slice 2E).

The contract these rows pin is the published exit table: a malformed or
truncated artifact is *incomplete analysis* (4), never a finding, never a clean
result, and never a traceback. A saved document that is not a report is invalid
input (3).

Every case runs the command the user runs. The fixtures are generated by
``tests/hostile_fixtures.py``; no worker, corpus or network is involved.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import hostile_fixtures as hostile
import pytest
from harness import Runner


@dataclass
class Case:
    name: str
    payload: bytes
    stage: str
    status: str
    exit_code: int


SCAN_CASES = [
    Case("gzip-truncated-header", hostile.gzip_truncated_header(), "extraction", "FAILED", 4),
    Case("gzip-corrupt-body", hostile.gzip_corrupt_body(), "extraction", "FAILED", 4),
    Case("gzip-isize-lie", hostile.gzip_isize_lie(), "extraction", "FAILED", 4),
    Case("squashfs-huge-extent", hostile.squashfs_huge_extent(), "extraction", "FAILED", 4),
    Case("squashfs-future-version", hostile.squashfs_future_version(), "extraction", "FAILED", 4),
    Case("squashfs-zero-block", hostile.squashfs_zero_block_size(), "extraction", "FAILED", 4),
    Case("squashfs-magic-only", hostile.squashfs_magic_only(), "extraction", "FAILED", 4),
    Case("fdt-totalsize-lie", hostile.fdt_totalsize_lie(), "boot_analysis", "FAILED", 4),
    Case("fdt-struct-offset-lie", hostile.fdt_struct_offset_lie(), "boot_analysis", "FAILED", 4),
    Case("fdt-header-only", hostile.fdt_header_only(), "boot_analysis", "FAILED", 4),
    Case("fdt-deep-nesting", hostile.fdt_deep_nesting(), "boot_analysis", "FAILED", 4),
    Case("fit-out-of-bounds", hostile.fit_out_of_bounds(), "boot_analysis", "PARTIAL", 4),
    Case("fit-truncated", hostile.fit_truncated(), "boot_analysis", "FAILED", 4),
    # Slice 3A part 3: a CPIO archive is header-validated before a byte is read.
    Case("cpio-data-size-lie", hostile.cpio_data_size_lie(), "extraction", "FAILED", 4),
    Case("cpio-traversal-name", hostile.cpio_traversal_name(), "extraction", "FAILED", 4),
    Case("cpio-no-trailer", hostile.cpio_no_trailer(), "extraction", "FAILED", 4),
    Case("cpio-binary-magic", hostile.cpio_binary_magic(), "extraction", "FAILED", 4),
]


def _scan(
    runner: Runner,
    work: Path,
    target: Path,
    *extra: str,
    env: dict[str, str] | None = None,
) -> tuple[int, dict | None, str]:
    out = work / f"report-{target.stem}.json"
    completed = runner(
        ["scan", str(target), "--offline", "--format", "json", "--out", str(out), *extra],
        cwd=work,
        env=env,
    )
    document = json.loads(out.read_text()) if out.is_file() else None
    return completed.returncode, document, completed.stdout + completed.stderr


def _stage(document: dict, stage_id: str) -> dict:
    return next(item for item in document["stages"] if item["stage"] == stage_id)


@pytest.mark.parametrize("case", SCAN_CASES, ids=[case.name for case in SCAN_CASES])
def test_hostile_artifact_is_incomplete_not_a_traceback(
    case: Case, runner: Runner, temp_dir: Path
) -> None:
    """A lie about size, offset or structure becomes exit 4, never a crash."""
    target = temp_dir / f"{case.name}.bin"
    target.write_bytes(case.payload)

    exit_code, document, output = _scan(runner, temp_dir, target)

    assert "Traceback" not in output, output
    assert exit_code == case.exit_code, output
    assert document is not None, "a report is still delivered for exit 4"
    assert document["outcome"]["exit_code"] == case.exit_code
    assert document["assessment"]["completion"] == "INCOMPLETE"
    stage = _stage(document, case.stage)
    assert stage["status"] == case.status
    assert stage["reason"], "an incomplete stage states why"


def test_an_oversized_package_database_is_a_failed_stage(runner: Runner, temp_dir: Path) -> None:
    """The opkg reader has a budget; exceeding it fails the stage, not the process."""
    tree = temp_dir / "tree"
    (tree / "usr" / "lib" / "opkg").mkdir(parents=True)
    (tree / "etc").mkdir()
    (tree / "etc" / "passwd").write_text("root:x:0:0:root:/root:/bin/sh\n")
    (tree / "usr" / "lib" / "opkg" / "status").write_bytes(hostile.opkg_oversized(mebibytes=3))

    # The database budget is derived from the configured text-file ceiling, so a
    # 2 MiB ceiling makes the 3 MiB database exceed it deterministically.
    exit_code, document, output = _scan(
        runner,
        temp_dir,
        tree,
        "--input-tree",
        env={"IOT_HARDWARE_SCANNER_MAX_SCAN_FILE_SIZE_MB": "2"},
    )

    assert "Traceback" not in output, output
    assert exit_code == 4, output
    assert document is not None
    stage = _stage(document, "opkg_inventory")
    assert stage["status"] == "FAILED"
    assert "budget" in stage["reason"]


def test_binary_garbage_in_a_package_database_does_not_crash(
    runner: Runner, temp_dir: Path
) -> None:
    """Invalid UTF-8 and NUL runs are data, not an exception."""
    tree = temp_dir / "tree"
    (tree / "usr" / "lib" / "opkg").mkdir(parents=True)
    (tree / "etc").mkdir()
    (tree / "etc" / "passwd").write_text("root:x:0:0:root:/root:/bin/sh\n")
    (tree / "usr" / "lib" / "opkg" / "status").write_bytes(hostile.opkg_binary_garbage())

    exit_code, document, output = _scan(runner, temp_dir, tree, "--input-tree")

    assert "Traceback" not in output, output
    assert exit_code in (0, 2), output
    assert document is not None
    assert document["stages"], "the stages are still reported"


@pytest.mark.parametrize(
    ("name", "document"),
    hostile.hostile_documents(),
    ids=[name for name, _ in hostile.hostile_documents()],
)
def test_a_hostile_saved_document_is_invalid_input(
    name: str, document: dict, runner: Runner, temp_dir: Path
) -> None:
    """``report`` rejects a malformed document with exit 3 and one line."""
    target = temp_dir / f"{name}.json"
    target.write_text(json.dumps(document))

    completed = runner(["report", str(target), "--format", "json"], cwd=temp_dir)
    output = completed.stdout + completed.stderr

    assert "Traceback" not in output, output
    assert completed.returncode == 3, output
    assert "unrecognised report document" in output or "cannot read" in output


