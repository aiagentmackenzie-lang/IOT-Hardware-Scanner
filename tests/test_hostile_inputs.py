def test_compare_and_sbom_reject_a_hostile_document(runner: Runner, temp_dir: Path) -> None:
    """The other two document consumers share the same validation."""
    base = temp_dir / "base.json"
    target = temp_dir / "target.json"
    base.write_text(json.dumps({"schema_version": 6, "assessment": "nope"}))
    target.write_text(json.dumps({"schema_version": 6, "findings": "nope"}))

    compared = runner(["compare", str(base), str(target)], cwd=temp_dir)
    assert "Traceback" not in (compared.stdout + compared.stderr)
    assert compared.returncode == 3

    exported = runner(["sbom", str(target)], cwd=temp_dir)
    assert "Traceback" not in (exported.stdout + exported.stderr)
    assert exported.returncode == 3


def test_the_extraction_member_validator_rejects_escaping_names() -> None:
    """The worker's return path cannot write outside the tree it was given."""
    from iot_hardware_scanner.scanner.extraction_worker import _safe_member_name

    assert not _safe_member_name("../escape")
    assert not _safe_member_name("/etc/passwd")
    assert not _safe_member_name("a/../../b")
    assert not _safe_member_name("~/.ssh/authorized_keys")
    assert _safe_member_name("etc/passwd")
    assert _safe_member_name("./bin/busybox")
